"""
Utility Script: Sync Processed Parquet Tables to JSON Mirrors
Distributed Cyber Threat Intelligence Platform

Reads all Parquet datasets generated by Spark (including multi-part files)
and exports clean JSON files into data/processed/ for instant Streamlit UI consumption.
"""

import json
from pathlib import Path
import pandas as pd
import pyarrow.parquet as pq

BASE_DIR = Path(__file__).resolve().parent.parent
PROC_DIR = BASE_DIR / "data" / "processed"

MAPPINGS = {
    "attack_distribution.parquet": "attack_stats.json",
    "protocol_distribution.parquet": "protocol_stats.json",
    "hourly_attack_intensity.parquet": "hourly_stats.json",
    "severity_distribution.parquet": "severity_stats.json",
    "top_attacking_ips.parquet": "ip_threat_frequency.json",
    "top_targeted_ips.parquet": "top_targeted_ips.json",
    "network_timeline_hourly.parquet": "timeline_stats.json",
    "ip_risk_scores.parquet": "ip_reputation.json",
}


def sync_all():
    print("=" * 60)
    print("  SYNCING PARQUET ANALYTICS TO LOCAL JSON CACHES")
    print("=" * 60)
    
    total_synced = 0
    for pq_name, json_name in MAPPINGS.items():
        pq_path = PROC_DIR / pq_name
        json_path = PROC_DIR / json_name
        
        if not pq_path.exists():
            print(f"[-] Missing: {pq_name}")
            continue
            
        parts = list(pq_path.glob("part-*.parquet"))
        if not parts:
            print(f"[-] No part files in {pq_name}")
            continue
            
        dfs = []
        for p in parts:
            dfs.append(pq.read_table(str(p)).to_pandas())
        df = pd.concat(dfs, ignore_index=True)
        
        # Convert timestamps/dates to string if present
        for col in df.columns:
            if pd.api.types.is_datetime64_any_dtype(df[col]):
                df[col] = df[col].astype(str)
                
        records = df.to_dict(orient="records")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(records, f, indent=2, default=str)
            
        print(f"  [OK] {pq_name:<32} -> {json_name:<24} ({len(records):>5,} rows)")
        total_synced += 1
        
    print("=" * 60)
    print(f"[+] Successfully synced {total_synced} tables to JSON caches.")
    print("=" * 60)


if __name__ == "__main__":
    sync_all()
